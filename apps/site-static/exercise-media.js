window.fitcoreExerciseMedia = function fitcoreExerciseMedia(exercicio) {
  const media = window.FITCORE_EXERCISE_MEDIA;
  const slug = String(exercicio?.slug || "");
  const sourceId = String(exercicio?.source_id || "");
  const bySlug = media.bySlug[slug] || null;
  const bySource = sourceId
    ? Object.values(media.bySlug).find((item) => item.gif && item.gif.includes(`/${sourceId}-`))
    : null;
  return {
    ...media.defaults,
    ...(bySlug || bySource || {}),
  };
};
